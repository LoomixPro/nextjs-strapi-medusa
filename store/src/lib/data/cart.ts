"use server"

import { sdk } from "@lib/config"
import medusaError from "@lib/util/medusa-error"
import { HttpTypes } from "@medusajs/types"
import { revalidateTag, revalidatePath } from "next/cache"
import { redirect } from "next/navigation"
import {
  getAuthHeaders,
  getCacheOptions,
  getCacheTag,
  getCartId,
  removeCartId,
  setCartId,
} from "./cookies"
import { getRegion } from "./regions"
import { getLocale } from "@lib/data/locale-actions"

async function revalidateCartCaches() {
  const cartCacheTag = await getCacheTag("carts")
  if (cartCacheTag) {
    revalidateTag(cartCacheTag, "max")
  }
  revalidateTag("carts", "max")
  revalidatePath("/", "layout")
}

async function revalidateFulfillmentCache() {
  const fulfillmentCacheTag = await getCacheTag("fulfillment")
  if (fulfillmentCacheTag) {
    revalidateTag(fulfillmentCacheTag, "max")
  }
}

/**
 * Retrieves a cart by its ID. If no ID is provided, it will use the cart ID from the cookies.
 * @param cartId - optional - The ID of the cart to retrieve.
 * @returns The cart object if found, or null if not found.
 */
export async function retrieveCart(cartId?: string, fields?: string) {
  const id = cartId || (await getCartId())
  fields ??=
    "*items, *region, *items.product, *items.variant, *items.variant.translations, *items.thumbnail, *items.metadata, +items.total, *promotions, +shipping_methods.name"

  if (!id) {
    return null
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  const next = {
    ...(await getCacheOptions("carts")),
  }

  const cart = await sdk.client
    .fetch<HttpTypes.StoreCartResponse>(`/store/carts/${id}`, {
      method: "GET",
      query: {
        fields,
      },
      headers,
      next,
      cache: "force-cache",
    })
    .then(({ cart }: { cart: HttpTypes.StoreCart }) => cart)
    .catch(() => null)

  if (!cart || cart.completed_at) {
    return null
  }

  return cart
}

export async function getOrSetCart(countryCode: string) {
  const region = await getRegion(countryCode)

  if (!region) {
    throw new Error(`Region not found for country code: ${countryCode}`)
  }

  let cart = await retrieveCart(undefined, "id,region_id,currency_code")

  const headers = {
    ...(await getAuthHeaders()),
  }

  if (!cart) {
    const locale = await getLocale()
    const cartResp = await sdk.store.cart.create(
      { region_id: region.id, locale: locale || undefined },
      {},
      headers
    )
    cart = cartResp.cart

    await setCartId(cart.id)
    await revalidateCartCaches()
  }

  if (
    cart &&
    (cart?.region_id !== region.id ||
      cart?.currency_code !== region.currency_code)
  ) {
    await sdk.store.cart.update(cart.id, { region_id: region.id }, {}, headers)
    await revalidateCartCaches()
  }

  return cart
}

export async function updateCart(data: HttpTypes.StoreUpdateCart) {
  const cartId = await getCartId()

  if (!cartId) {
    throw new Error("No existing cart found, please create one before updating")
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  return sdk.store.cart
    .update(cartId, data, {}, headers)
    .then(async ({ cart }: { cart: HttpTypes.StoreCart }) => {
      await revalidateCartCaches()
      await revalidateFulfillmentCache()
      return cart
    })
    .catch(medusaError)
}

export async function addToCart({
  variantId,
  quantity,
  countryCode,
}: {
  variantId: string
  quantity: number
  countryCode: string
}) {
  if (!variantId) {
    return "Missing variant ID when adding to cart"
  }

  const cart = await getOrSetCart(countryCode)

  if (!cart) {
    return "Error retrieving or creating cart"
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  try {
    await sdk.store.cart
      .createLineItem(
        cart.id,
        {
          variant_id: variantId,
          quantity,
        },
        {},
        headers
      )
      .then(async () => {
        await revalidateCartCaches()
        await revalidateFulfillmentCache()
      })
      .catch(medusaError)
  } catch (e: any) {
    const errorMsg = e.message || ""
    if (errorMsg.toLowerCase().includes("completed")) {
      await removeCartId()
      const newCart = await getOrSetCart(countryCode)
      if (newCart) {
        try {
          await sdk.store.cart.createLineItem(
            newCart.id,
            { variant_id: variantId, quantity },
            {},
            headers
          )
          await revalidateCartCaches()
          await revalidateFulfillmentCache()
          return
        } catch (innerErr: any) {
          return innerErr.message
        }
      }
    }
    return errorMsg
  }
}

