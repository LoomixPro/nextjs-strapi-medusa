const fs = require("fs")
const path = require("path")

const SRC_DIR = path.join(__dirname, "../src/modules")

// Helper to convert kebab-case to PascalCase
function toPascalCase(str) {
  return str
    .replace(/[^a-zA-Z0-9-]/g, "")
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")
}

function walk(dir) {
  if (!fs.existsSync(dir)) return
  const files = fs.readdirSync(dir)
  for (const file of files) {
    const fullPath = path.join(dir, file)
    if (fs.statSync(fullPath).isDirectory()) {
      if (file === "styles") {
        generateRegistryForStylesDir(fullPath, dir)
      } else {
        walk(fullPath)
      }
    }
  }
}

function generateRegistryForStylesDir(stylesDir, parentDir) {
  const styleItems = fs.readdirSync(stylesDir).filter((f) => {
    return f.startsWith("style-")
  })

  if (styleItems.length === 0) return

  const registryPath = path.join(parentDir, "registry.ts")
  const componentPrefix = toPascalCase(path.basename(parentDir))

  let imports = 'import React from "react";\n'
  let mapEntries = ""
  let summaryMapEntries = ""
  let hasSummary = false

  styleItems.forEach((item) => {
    const itemPath = path.join(stylesDir, item)
    const isDir = fs.statSync(itemPath).isDirectory()
    const styleName = isDir ? item : item.replace(/\.tsx?$/, "")

    if (mapEntries.includes(`"${styleName}"`)) return

    const importName = `${componentPrefix}${toPascalCase(styleName)}`
    imports += `import ${importName} from "./styles/${styleName}";\n`
    mapEntries += `  "${styleName}": ${importName},\n`

    // Check for summary.tsx in the style directory
    if (isDir) {
      const summaryPathTsx = path.join(itemPath, "summary.tsx")
      const summaryPathTs = path.join(itemPath, "summary.ts")

      if (fs.existsSync(summaryPathTsx) || fs.existsSync(summaryPathTs)) {
        hasSummary = true
        const summaryImportName = `${componentPrefix}${toPascalCase(styleName)}Summary`
        imports += `import ${summaryImportName} from "./styles/${styleName}/summary";\n`
        summaryMapEntries += `  "${styleName}": ${summaryImportName},\n`
      }
    }
  })

  let fileContent = `// Automatically generated by scripts/generate-style-registries.js
// Do not edit this file manually.

${imports}
export const STYLES: Record<string, React.ComponentType<any>> = {
${mapEntries}};
`

  if (hasSummary) {
    fileContent += `\nexport const SUMMARY_STYLES: Record<string, React.ComponentType<any>> = {\n${summaryMapEntries}};\n`
  }

  fs.writeFileSync(registryPath, fileContent, "utf8")
  console.log(`Generated registry at ${registryPath}`)

  const relKey = path.relative(SRC_DIR, parentDir).replace(/\\/g, "/")
  installedStylesMap[relKey] = styleItems
    .map((item) => {
      const itemPath = path.join(stylesDir, item)
      const isDir = fs.statSync(itemPath).isDirectory()
      return isDir ? item : item.replace(/\.tsx?$/, "")
    })
    .sort()
}

const installedStylesMap = {}

console.log("Scanning for style directories to generate registries...")
walk(SRC_DIR)
console.log("Finished generating registries.")

// Write installed-styles.json manifest
try {
  const configDir = path.join(__dirname, "../src/lib/config")
  const publicDir = path.join(__dirname, "../public")
  if (!fs.existsSync(configDir)) fs.mkdirSync(configDir, { recursive: true })
  if (!fs.existsSync(publicDir)) fs.mkdirSync(publicDir, { recursive: true })

  const jsonContent = JSON.stringify(installedStylesMap, null, 2) + "\n"
  fs.writeFileSync(
    path.join(configDir, "installed-styles.json"),
    jsonContent,
    "utf8"
  )
  fs.writeFileSync(
    path.join(publicDir, "installed-styles.json"),
    jsonContent,
    "utf8"
  )
  console.log("Saved installed-styles.json manifest to config and public.")
} catch (e) {
  console.warn("Failed to write installed-styles.json manifest:", e.message)
}

// PROFILE AUTO-GENERATOR
const profileDir = path.join(
  __dirname,
  "../src/modules/account/templates/profile"
)
const profileRegistryPath = path.join(profileDir, "registry.ts")

let existingRegistry = ""
if (fs.existsSync(profileRegistryPath)) {
  existingRegistry = fs.readFileSync(profileRegistryPath, "utf8")
  // Remove existing auto-generated profile stuff so it doesn't duplicate
  const splitIndex = existingRegistry.indexOf(
    "// --- PROFILE COMPONENTS AUTO-GENERATED ---"
  )
  if (splitIndex !== -1) {
    existingRegistry = existingRegistry.substring(0, splitIndex).trim()
  }
}

let componentsImports = ""
let sharedComponentsMap = ""
let stylesComponentsMaps = ""

// 1. Shared components
const sharedComponentsDir = path.join(profileDir, "components")
if (fs.existsSync(sharedComponentsDir)) {
  const sharedItems = fs.readdirSync(sharedComponentsDir).filter((f) => {
    const fullPath = path.join(sharedComponentsDir, f)
    if (!fs.statSync(fullPath).isDirectory()) return false
    return (
      fs.existsSync(path.join(fullPath, "index.tsx")) ||
      fs.existsSync(path.join(fullPath, "index.ts"))
    )
  })
  sharedItems.forEach((item) => {
    const importName = `Shared${toPascalCase(item)}`
    componentsImports += `import ${importName} from "./components/${item}";\n`
    sharedComponentsMap += `  "${item}": ${importName},\n`
  })
}

// 2. Style-specific components
const profileStylesDir = path.join(profileDir, "styles")
if (fs.existsSync(profileStylesDir)) {
  const styles = fs
    .readdirSync(profileStylesDir)
    .filter(
      (f) =>
        f.startsWith("style-") &&
        fs.statSync(path.join(profileStylesDir, f)).isDirectory()
    )

  styles.forEach((style) => {
    const styleComponentsDir = path.join(profileStylesDir, style, "components")
    let mapEntries = ""

    if (fs.existsSync(styleComponentsDir)) {
      const items = fs.readdirSync(styleComponentsDir).filter((f) => {
        const fullPath = path.join(styleComponentsDir, f)
        if (!fs.statSync(fullPath).isDirectory()) return false
        return (
          fs.existsSync(path.join(fullPath, "index.tsx")) ||
          fs.existsSync(path.join(fullPath, "index.ts"))
        )
      })
      items.forEach((item) => {
        const importName = `${toPascalCase(style)}${toPascalCase(item)}`
        componentsImports += `import ${importName} from "./styles/${style}/components/${item}";\n`
        mapEntries += `    "${item}": ${importName},\n`
      })
    }

    stylesComponentsMaps += `  "${style}": {\n${mapEntries}  },\n`
  })
}

const finalRegistry = `${existingRegistry}

// --- PROFILE COMPONENTS AUTO-GENERATED ---
${componentsImports}
export const SHARED_PROFILE_COMPONENTS: Record<string, React.ComponentType<any>> = {
${sharedComponentsMap}};

export const STYLE_PROFILE_COMPONENTS: Record<string, Record<string, React.ComponentType<any>>> = {
${stylesComponentsMaps}};
`

fs.writeFileSync(profileRegistryPath, finalRegistry, "utf8")
console.log("Profile components added to registry.ts")
